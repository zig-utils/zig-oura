import { $ } from 'bun'
const zig = process.env.ZIG_OURA || (await Bun.file('pantry/.bin/zig').exists() ? './pantry/.bin/zig' : 'zig')
await $`${zig} build test`
await $`${zig} build -Doptimize=ReleaseFast`
await $`${zig} build wasm`
const bytes = new Uint8Array(await Bun.file('zig-out/bin/oura.wasm').arrayBuffer())
await Bun.write('bindings/wasm-bytes.ts', `// Generated by scripts/build.ts from the native Zig implementation.\nexport const wasmBytes: number[] = ${JSON.stringify([...bytes])}\n`)
const built = await Bun.build({ entrypoints: ['bindings/index.ts'], outdir: 'dist', target: 'browser', format: 'esm', minify: true })
if (!built.success) throw new Error(built.logs.map(log => log.message).join('; '))
